import 'package:equatable/equatable.dart';

class ProjectReportSection extends Equatable {
  const ProjectReportSection({
    required this.id,
    required this.companyId,
    required this.reportId,
    required this.sectionKey,
    required this.sectionTitle,
    required this.sectionType,
    required this.sortOrder,
    required this.contentText,
    required this.contentJson,
    required this.isAutoGenerated,
    required this.createdAt,
    required this.updatedAt,
  });

  final String id;
  final String companyId;
  final String reportId;
  final String sectionKey;
  final String sectionTitle;
  final String sectionType;
  final int sortOrder;
  final String contentText;
  final Map<String, dynamic> contentJson;
  final bool isAutoGenerated;
  final DateTime createdAt;
  final DateTime updatedAt;

  factory ProjectReportSection.fromMap(Map<String, dynamic> map) {
    return ProjectReportSection(
      id: map['id'] as String,
      companyId: map['company_id'] as String,
      reportId: map['report_id'] as String,
      sectionKey: (map['section_key'] as String?) ?? '',
      sectionTitle: (map['section_title'] as String?) ?? '',
      sectionType: (map['section_type'] as String?) ?? 'text',
      sortOrder: _toInt(map['sort_order']),
      contentText: (map['content_text'] as String?) ?? '',
      contentJson: _toMap(map['content_json']),
      isAutoGenerated: (map['is_auto_generated'] as bool?) ?? false,
      createdAt: DateTime.parse(map['created_at'] as String),
      updatedAt: DateTime.parse(map['updated_at'] as String),
    );
  }

  Map<String, dynamic> toInsertMap() {
    return <String, dynamic>{
      'company_id': companyId,
      'report_id': reportId,
      'section_key': sectionKey,
      'section_title': sectionTitle,
      'section_type': sectionType,
      'sort_order': sortOrder,
      'content_text': contentText,
      'content_json': contentJson,
      'is_auto_generated': isAutoGenerated,
      'created_at': createdAt.toIso8601String(),
      'updated_at': updatedAt.toIso8601String(),
    };
  }

  static int _toInt(dynamic value) {
    if (value == null) {
      return 0;
    }
    if (value is int) {
      return value;
    }
    return int.tryParse(value.toString()) ?? 0;
  }

  static Map<String, dynamic> _toMap(dynamic value) {
    if (value is Map<String, dynamic>) {
      return value;
    }
    if (value is Map) {
      return value.map(
        (key, val) => MapEntry(key.toString(), val),
      );
    }
    return <String, dynamic>{};
  }

  @override
  List<Object?> get props => [
        id,
        companyId,
        reportId,
        sectionKey,
        sectionTitle,
        sectionType,
        sortOrder,
        contentText,
        contentJson,
        isAutoGenerated,
        createdAt,
        updatedAt,
      ];
}
