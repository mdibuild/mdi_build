class ReportExportService {
  Future<void> exportPdf({
    required String projectName,
    required ProjectReport report,
    required List<ProjectReportSection> sections,
    required List<ProjectReportSource> sources,
  }) async {
    final bytes = await buildPdf(
      projectName: projectName,
      report: report,
      sections: sections,
      sources: sources,
    );

    await Printing.layoutPdf(
      name: '${_safeFileName(report.title)}.pdf',
      onLayout: (format) async => bytes,
    );
  }

  Future<Uint8List> buildPdf({
    required String projectName,
    required ProjectReport report,
    required List<ProjectReportSection> sections,
    required List<ProjectReportSource> sources,
  }) async {
    final regularFont = await PdfGoogleFonts.notoSansRegular();
    final boldFont = await PdfGoogleFonts.notoSansBold();

    final pdf = pw.Document(
      theme: pw.ThemeData.withFont(
        base: regularFont,
        bold: boldFont,
      ),
    );

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(24),
        build: (context) => [
          _header(
            projectName: projectName,
            report: report,
            boldFont: boldFont,
          ),
          pw.SizedBox(height: 16),
          _summaryCard(report),
          pw.SizedBox(height: 16),
          ...sections.map((section) => _sectionBlock(section, boldFont)),
          if (sources.isNotEmpty) ...[
            pw.SizedBox(height: 16),
            _sourcesBlock(sources, boldFont),
          ],
        ],
      ),
    );

    return Uint8List.fromList(await pdf.save());
  }

